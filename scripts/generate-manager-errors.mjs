import { readdir, readFile } from 'node:fs/promises';
import { writeGenerated } from './write-generated.mjs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const codes = new Set([
  'VERSION_CONFLICT',
  'TASK_VERSION_CONFLICT',
  'VALIDATION_FAILED',
  'NETWORK_ERROR',
  'INVALID_RESPONSE',
  'HTTP_ERROR',
  'PASSKEY_FAILED',
  'PASSKEY_CANCELLED',
  'WEBAUTHN_UNAVAILABLE',
]);
async function scan(path) {
  for (const entry of await readdir(path, { withFileTypes: true })) {
    const file = resolve(path, entry.name);
    if (entry.isDirectory()) await scan(file);
    else if (entry.name.endsWith('.ts')) {
      const source = await readFile(file, 'utf8');
      for (const match of source.matchAll(/domainError\(\s*['"]([A-Z][A-Z0-9_]+)['"]/g))
        codes.add(match[1]);
      for (const block of source.matchAll(/(?:ERROR_CODES|ErrorCodes)\s*=\s*\[([\s\S]*?)\]/g))
        for (const match of block[1].matchAll(/['"]([A-Z][A-Z0-9_]+)['"]/g)) codes.add(match[1]);
    }
  }
}
for (const area of [
  'modules/manager',
  'modules/finance',
  'modules/schedule',
  'modules/identity',
  'modules/notifications',
  'core',
])
  await scan(resolve(root, 'apps/api/src', area));
await writeGenerated(
  resolve(root, 'packages/api-contracts/src/generated/manager-error-codes.ts'),
  `// Generated by scripts/generate-manager-errors.mjs. Do not edit.\nexport const MANAGER_CLIENT_ERROR_CODES = ${JSON.stringify([...codes].sort(), null, 2)} as const;\nexport type AnyManagerErrorCode = (typeof MANAGER_CLIENT_ERROR_CODES)[number];\n`,
);
console.log(`Manager client error catalog: ${codes.size} codes`);
